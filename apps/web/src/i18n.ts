const dict: Record<Lang, Record<TKey, string>> = { en, ar };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Translate an enum value with a prefix (e.g. 'st.' + status); falls back to the raw value. */
export function translateEnum(lang: Lang, prefix: string, value: string | null | undefined): string {
  if (!value) return '—';
  const k = `${prefix}${value}` as TKey;
  return k in en ? translate(lang, k) : value;
}

export interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  te: (prefix: string, value: string | null | undefined) => string;
  /** pick the Arabic or English variant of a bilingual field */
  pick: (enValue: string | null | undefined, arValue: string | null | undefined) => string;
  fmtDate: (iso: string | null | undefined) => string;
  fmtMoney: (n: number | string | null | undefined, currency?: string) => string;
}

export const I18nContext = createContext<I18n | null>(null);

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('I18nContext missing');
  return ctx;
}

export function makeI18n(lang: Lang, setLang: (l: Lang) => void): I18n {
  const locale = lang === 'ar' ? 'ar-KW' : 'en-GB';
  return {
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
    te: (prefix, value) => translateEnum(lang, prefix, value),
    pick: (e, a) => (lang === 'ar' ? a || e || '' : e || a || ''),
    fmtDate: (iso) => {
      if (!iso) return '—';
      const d = new Date(iso);
      if (Number.isNaN(d.getTime())) return iso;
      return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short', timeZone: 'Asia/Kuwait' }).format(d);
    },
    fmtMoney: (n, currency = 'KWD') => {
      if (n === null || n === undefined || n === '') return '—';
      const v = typeof n === 'string' ? Number(n) : n;
      if (Number.isNaN(v)) return String(n);
      try {
        return new Intl.NumberFormat(locale, { style: 'currency', currency, maximumFractionDigits: 3 }).format(v);
      } catch {
        return `${v.toLocaleString(locale)} ${currency}`;
      }
    },
  };
}
