const humanise = (code: string) => code.toLowerCase().replace(/_/g, ' ').replace(/^./, (c) => c.toUpperCase());

/** Readable label for an audit action code; unknown codes fall back to a humanised code. */
export function auditLabel(lang: Lang, code: string): string {
  const hit = L[code];
  return hit ? hit[lang === 'ar' ? 1 : 0] : humanise(code);
}
