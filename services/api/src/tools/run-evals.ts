// npm run evals — runs agents/evals/*.json against the REAL clarification agent and writes
// agents/evals/results.md with every raw answer, per-question pass/fail and true totals; then runs
// agents/evals/agents/*.json against the six Phase 1 agents (classifier, notice drafter, relevance matcher,
// evaluation narrator, grade reviewer, supervisor assistant) and writes agents/evals/agents/results.md.
// Arguments: "clarification" or "agents" to run one part only; any other argument filters by case id.
// Scoring: fact match (all expected keywords, case/diacritic-insensitive) AND citation section match;
// "not found" questions pass only when the agent returns notFound=true.
// Exits 0 even when the pass rate is low; non-zero only when the evals cannot run at all.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { findRepoRoot, loadRepoEnv } from '../ai/tools/env.js';
import { markdownToDocText } from '../ai/tools/markdown-doc.js';
import { scoreAnswer, validateEvalFile, type EvalFile, type EvalScore } from '../ai/tools/evals.js';
import { createAiService } from '../ai/index.js';
import { missingSettings, readAiConfig } from '../ai/config.js';
import type { ClarificationDraft } from '../ai/types.js';
import { runAgentCase, scoreAgentCase, validateAgentEvalFile, type AgentEvalScore } from '../ai/tools/agent-evals.js';

interface Row {
  file: string; id: string; language: string; question: string; expectNotFound: boolean;
  draft?: ClarificationDraft; rawText?: string; model?: string; error?: string; ms: number; score?: EvalScore; repaired?: boolean;
}

const md = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

async function main(): Promise<number> {
  const root = findRepoRoot();
  loadRepoEnv(root);
  const cfg = readAiConfig();
  const missing = missingSettings(cfg);
  if (missing.length) { console.error(`Cannot run evals: missing ${missing.join(', ')} in ${root}/.env`); return 2; }

  const args = process.argv.slice(2).flatMap((a) => a.split(',')).filter(Boolean);
  const parts = new Set<string>(args.filter((a) => a === 'clarification' || a === 'agents'));
  const only = new Set(args.filter((a) => !parts.has(a)));
  const runClar = !parts.size || parts.has('clarification');
  const runAgents = !parts.size || parts.has('agents');
  const codeA = runClar ? await clarification(root, cfg, only) : 0;
  const codeB = runAgents ? await agentEvals(root, cfg, only) : 0;
  return Math.max(codeA, codeB);
}

async function clarification(root: string, cfg: ReturnType<typeof readAiConfig>, only: Set<string>): Promise<number> {
  const dir = join(root, 'agents', 'evals');
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  if (!files.length) { console.error(`No eval files in ${dir}`); return 2; }

  const ai = createAiService();
  const rows: Row[] = [];
  const started = new Date();
  for (const f of files) {
    const set: EvalFile = validateEvalFile(JSON.parse(readFileSync(join(dir, f), 'utf8')), f);
    const doc = markdownToDocText(set.documentId, readFileSync(join(dir, set.document), 'utf8'));
    for (const q of set.questions) {
      if (only.size && !only.has(q.id)) continue;
      const t0 = Date.now();
      const row: Row = { file: f, id: q.id, language: q.language, question: q.question, expectNotFound: !!q.expectNotFound, ms: 0 };
      try {
        const res = await ai.draftClarification({ tender: set.tender, question: q.question, documents: [doc], priorAnswers: [] });
        const meta = res.raw as { text?: string; repaired?: boolean } | undefined;
        row.draft = res.output; row.model = res.model; row.rawText = meta?.text; row.repaired = meta?.repaired;
        row.score = scoreAnswer(q, res.output);
      } catch (e) {
        row.error = (e as Error).message;
      }
      row.ms = Date.now() - t0;
      rows.push(row);
      const verdict = row.error ? 'ERROR' : row.score!.pass ? 'PASS' : 'FAIL';
      console.log(`${q.id.padEnd(6)} ${verdict.padEnd(5)} ${row.ms} ms${row.error ? `  ${row.error.slice(0, 160)}` : ''}`);
    }
  }

  const total = rows.length;
  const passed = rows.filter((r) => r.score?.pass).length;
  const errors = rows.filter((r) => r.error).length;
  const answerable = rows.filter((r) => !r.expectNotFound);
  const nf = rows.filter((r) => r.expectNotFound);
  const pct = (n: number, d: number) => (d ? `${((100 * n) / d).toFixed(1)}%` : 'n/a');
  const byLang = (l: string) => { const rs = answerable.filter((r) => r.language === l); return `${rs.filter((r) => r.score?.pass).length}/${rs.length}`; };
  const models = [...new Set(rows.map((r) => r.model).filter(Boolean))].join(', ') || '(not reported)';

  const out: string[] = [];
  out.push('# Clarification agent eval results', '');
  out.push(`Generated by \`npm run evals\` (services/api/src/tools/run-evals.ts) against the live watsonx Orchestrate agent \`${cfg.agents.clarification}\`. Every answer below is the agent's real output; nothing is hand-edited.`, '');
  out.push(`- Run started: ${started.toISOString()}`);
  out.push(`- Run finished: ${new Date().toISOString()}`);
  out.push(`- Instance host: ${(() => { try { return new URL(cfg.instanceUrl).host; } catch { return '(invalid URL)'; } })()}`);
  out.push(`- Agent model (llm): ${models}`);
  out.push(`- **Overall: ${passed}/${total} passed (${pct(passed, total)})**; errors: ${errors}`);
  out.push(`- Answerable questions: ${answerable.filter((r) => r.score?.pass).length}/${answerable.length} (EN ${byLang('en')}, AR ${byLang('ar')}); fact match ${answerable.filter((r) => r.score?.factMatch).length}/${answerable.length}; citation section match ${answerable.filter((r) => r.score?.citationMatch).length}/${answerable.length}`);
  out.push(`- Not-found questions correctly flagged: ${nf.filter((r) => r.score?.pass).length}/${nf.length}`, '');
  out.push('Scoring: PASS = all expected keywords present in the answer (case/diacritic-insensitive; alternatives allowed) AND at least one citation in an expected section AND notFound=false; for not-found questions PASS = notFound=true.', '');
  out.push('| ID | Lang | Result | Fact | Citation | notFound | Time (ms) |', '|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const s = r.score;
    const res = r.error ? 'ERROR' : s!.pass ? 'PASS' : 'FAIL';
    const yn = (v: boolean | null | undefined) => (v === null || v === undefined ? '—' : v ? 'yes' : 'no');
    out.push(`| ${r.id} | ${r.language} | ${res} | ${yn(s?.factMatch)} | ${yn(s?.citationMatch)} | ${r.draft ? String(r.draft.notFound) : '—'} | ${r.ms} |`);
  }
  out.push('', '## Per-question detail', '');
  for (const r of rows) {
    out.push(`### ${r.id} (${r.language}) — ${r.error ? 'ERROR' : r.score!.pass ? 'PASS' : 'FAIL'}`, '');
    out.push(`- Question: ${md(r.question)}`);
    if (r.error) { out.push(`- Error: ${md(r.error)}`, ''); continue; }
    out.push(`- Answer: ${md(r.draft!.answer)}`);
    out.push(`- notFound: ${r.draft!.notFound}; repair turn used: ${r.repaired ? 'yes' : 'no'}`);
    out.push(`- Citations: ${r.draft!.citations.length ? r.draft!.citations.map((c) => `[${md(c.section)}]${c.quote ? ` "${md(c.quote)}"` : ''}`).join('; ') : '(none)'}`);
    if (r.score?.missingKeywords.length) out.push(`- Missing expected keywords: ${r.score.missingKeywords.map(md).join(', ')}`);
    out.push('', '<details><summary>Raw agent text</summary>', '', '```', (r.rawText ?? '').replace(/```/g, "'''"), '```', '', '</details>', '');
  }
  const outPath = join(dir, 'results.md');
  writeFileSync(outPath, out.join('\n'), 'utf8');
  console.log(`\nPass rate: ${passed}/${total} (${pct(passed, total)}); errors: ${errors}. Written ${outPath}`);
  return total && errors === total ? 1 : 0;
}

interface AgentRow { file: string; id: string; agent: string; language: string; ms: number; output?: unknown; model?: string; repaired?: boolean; error?: string; score?: AgentEvalScore }

async function agentEvals(root: string, cfg: ReturnType<typeof readAiConfig>, only: Set<string>): Promise<number> {
  const dir = join(root, 'agents', 'evals', 'agents');
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  if (!files.length) { console.error(`No agent eval files in ${dir}`); return 2; }
  const ai = createAiService();
  const rows: AgentRow[] = [];
  const started = new Date();
  console.log('\nPhase 1 agents');
  for (const f of files) {
    const set = validateAgentEvalFile(JSON.parse(readFileSync(join(dir, f), 'utf8')), f);
    for (const c of set.cases) {
      if (only.size && !only.has(c.id)) continue;
      const row: AgentRow = { file: f, id: c.id, agent: cfg.agents[c.agent], language: c.language, ms: 0 };
      const t0 = Date.now();
      try {
        const res = await runAgentCase(ai, c);
        row.output = res.output; row.model = res.model; row.repaired = (res.raw as { repaired?: boolean } | undefined)?.repaired;
        row.score = scoreAgentCase(c, res.output);
      } catch (e) { row.error = (e as Error).message; }
      row.ms = Date.now() - t0;
      rows.push(row);
      const verdict = row.error ? 'ERROR' : row.score!.pass ? 'PASS' : 'FAIL';
      console.log(`${c.id.padEnd(11)} ${verdict.padEnd(5)} ${row.ms} ms${row.error ? `  ${row.error.slice(0, 160)}` : ''}`);
    }
  }
  const passed = rows.filter((r) => r.score?.pass).length;
  const errors = rows.filter((r) => r.error).length;
  const out: string[] = ['# Phase 1 agent eval results', ''];
  out.push('Generated by `npm run evals -- agents` against the live watsonx Orchestrate agents. Outputs are the agents\' real, validated answers (TenderFlow rejects invalid JSON, unknown codes/ids and numbers that are not in the input before scoring); nothing is hand-edited.', '');
  out.push(`- Run: ${started.toISOString()} → ${new Date().toISOString()}`);
  out.push(`- Models: ${[...new Set(rows.map((r) => r.model).filter(Boolean))].join(', ') || '(not reported)'}`);
  out.push(`- **Overall: ${passed}/${rows.length} passed**; errors (rejected or failed calls): ${errors}`, '');
  out.push('| ID | Agent | Lang | Result | Failed checks | Repair turn | Time (ms) |', '|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const failed = r.score?.checks.filter((c) => !c.ok).map((c) => `${c.name}${c.detail ? ` (${c.detail})` : ''}`).join('; ') ?? '';
    out.push(`| ${r.id} | ${r.agent} | ${r.language} | ${r.error ? 'ERROR' : r.score!.pass ? 'PASS' : 'FAIL'} | ${md(r.error ?? failed) || '—'} | ${r.repaired ? 'yes' : 'no'} | ${r.ms} |`);
  }
  out.push('', '## Outputs', '');
  for (const r of rows) out.push(`### ${r.id}`, '', '```json', JSON.stringify(r.output ?? { error: r.error }, null, 1).replace(/```/g, "'''"), '```', '');
  const outPath = join(dir, 'results.md');
  writeFileSync(outPath, out.join('\n'), 'utf8');
  console.log(`\nAgents pass rate: ${passed}/${rows.length}; errors: ${errors}. Written ${outPath}`);
  return rows.length && errors === rows.length ? 1 : 0;
}

main().then((code) => { process.exitCode = code; }, (e) => { console.error(`FAIL: ${(e as Error).message}`); process.exitCode = 1; });
