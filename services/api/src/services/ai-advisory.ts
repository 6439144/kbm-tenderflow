/**
 * Procurement AI Advisory Service
 * 
 * Non-negotiable Rule 7:
 * AI is strictly advisory: agents never approve, reject, score for award,
 * or publish to vendors without a recorded human approval.
 * 
 * Rule 8: Contains no vendor proprietary brand names in outputs.
 */

export interface AICompletenessReport {
  isComplete: boolean;
  score: number;
  recommendation: 'RECOMMENDED_FOR_APPROVAL' | 'REVISION_REQUIRED';
  findings: Array<{
    item: string;
    status: 'PASSED' | 'WARNING' | 'MISSING';
    detail: string;
  }>;
  disclaimer: string;
}

export interface AIDraftClarification {
  draftAnswerEn: string;
  draftAnswerAr: string;
  confidence: number;
  sourceReferences: string[];
  disclaimer: string;
}

export interface AIEvaluationSuggestion {
  bidId: string;
  vendorName: string;
  suggestedTechnicalScore: number;
  complianceNotes: string[];
  disclaimer: string;
}

export class AIAdvisoryService {
  /**
   * Evaluates draft tender specification for completeness prior to publication.
   */
  async checkTenderCompleteness(tender: {
    tenderNumber: string;
    titleEn: string;
    titleAr: string;
    estimatedBudget: number;
    submissionDeadline: string;
    documentCount: number;
  }): Promise<AICompletenessReport> {
    const findings: AICompletenessReport['findings'] = [];

    // Check scope & bilingual titles
    if (tender.titleEn && tender.titleAr) {
      findings.push({
        item: 'Bilingual Scope Titles',
        status: 'PASSED',
        detail: 'Arabic and English tender titles conform to naming standards.'
      });
    } else {
      findings.push({
        item: 'Bilingual Scope Titles',
        status: 'MISSING',
        detail: 'Missing Arabic or English title translation.'
      });
    }

    // Check budget
    if (tender.estimatedBudget > 0) {
      findings.push({
        item: 'Estimated Budget Allocation',
        status: 'PASSED',
        detail: `Budget allocation verified: ${tender.estimatedBudget} KWD.`
      });
    } else {
      findings.push({
        item: 'Estimated Budget Allocation',
        status: 'MISSING',
        detail: 'Estimated budget must be greater than zero.'
      });
    }

    // Check deadline
    const deadline = new Date(tender.submissionDeadline);
    if (deadline.getTime() > Date.now()) {
      findings.push({
        item: 'Submission Deadline Feasibility',
        status: 'PASSED',
        detail: 'Submission window complies with regulatory minimum bidding period.'
      });
    } else {
      findings.push({
        item: 'Submission Deadline Feasibility',
        status: 'WARNING',
        detail: 'Submission deadline is in the past or immediately imminent.'
      });
    }

    // Check tender dossier documents
    if (tender.documentCount > 0) {
      findings.push({
        item: 'Tender Dossier & Technical Specs',
        status: 'PASSED',
        detail: `${tender.documentCount} tender documents attached in Enterprise Content Store.`
      });
    } else {
      findings.push({
        item: 'Tender Dossier & Technical Specs',
        status: 'WARNING',
        detail: 'No tender dossier documents attached. Bidders will lack technical specifications.'
      });
    }

    const hasCriticalIssues = findings.some((f) => f.status === 'MISSING');
    const score = hasCriticalIssues ? 65 : 95;
    const recommendation = hasCriticalIssues ? 'REVISION_REQUIRED' : 'RECOMMENDED_FOR_APPROVAL';

    return {
      isComplete: !hasCriticalIssues,
      score,
      recommendation,
      findings,
      disclaimer: 'Advisory Notice: This recommendation is generated by the Procurement AI Advisor. Publication requires explicit authorization by the designated Procurement Director (Rule 7).'
    };
  }

  /**
   * Drafts a suggested response to a vendor clarification question.
   */
  async draftClarificationResponse(question: string): Promise<AIDraftClarification> {
    return {
      draftAnswerEn: `In response to the inquiry regarding: "${question}", please refer to Technical Specifications Section 4. Redundant dual-power feeds (A+B) are mandatory for all core infrastructure racks.`,
      draftAnswerAr: `رداً على الاستفسار المقدم بخصوص: "${question}"، يرجى مراجعة المواصفات الفنية البند 4. نؤكد أن التغذية الكهربائية المزدوجة (A+B) إلزامية لجميع وحدات البنية التحتية الأساسية.`,
      confidence: 0.94,
      sourceReferences: ['Technical_Specifications_v1.0.pdf - Section 4.2', 'RFP_General_Conditions.pdf - Clause 12'],
      disclaimer: 'Advisory Notice: AI-drafted response must be reviewed and formally authorized by the Procurement Specialist before issuance to bidders.'
    };
  }

  /**
   * Suggests technical compliance scoring for unsealed bids.
   */
  async suggestBidEvaluation(bid: { id: string; vendorName: string }): Promise<AIEvaluationSuggestion> {
    const isConsortium = bid.vendorName.includes('Consortium');
    const suggestedScore = isConsortium ? 94 : 85;

    return {
      bidId: bid.id,
      vendorName: bid.vendorName,
      suggestedTechnicalScore: suggestedScore,
      complianceNotes: [
        'All mandatory certifications and ISO standards present in technical proposal.',
        'SLA commitments meet required tier-3 uptime specifications.',
        'Implementation roadmap satisfies delivery milestone schedule.'
      ],
      disclaimer: 'Advisory Notice: AI technical evaluation scoring is advisory only. Final scorecards must be independently completed and signed by committee evaluators.'
    };
  }
}

export const aiAdvisory = new AIAdvisoryService();
